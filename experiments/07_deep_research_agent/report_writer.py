"""
Report synthesis and markdown formatting for Deep Research agent.
"""

from typing import List, Dict, Any


def synthesize_research_report(topic: str, plan: List[str], evidence: List[Dict[str, Any]], reflection_notes: List[str]) -> str:
    """Combines research phases into a comprehensive academic-style report."""
    
    report_lines = [
        f"# Comprehensive Research Dossier: {topic.title()}",
        "",
        "## 1. Executive Overview",
        f"This investigative report evaluates current developments, architectural methodologies, and industry consensus regarding **{topic}**. The findings below reflect an iterative Plan-Execute-Reflect-Refine research cycle.",
        "",
        "## 2. Research Plan & Sub-Topics Investigated",
    ]
    for idx, item in enumerate(plan, 1):
        report_lines.append(f"{idx}. {item}")

    report_lines.extend([
        "",
        "## 3. Key Findings & Empirical Evidence",
    ])

    for ev in evidence:
        report_lines.append(f"### Source: {ev.get('title', 'Unknown Reference')}")
        report_lines.append(f"- **URL**: {ev.get('url', 'N/A')}")
        report_lines.append(f"- **Evidence**: {ev.get('snippet', '')}")
        report_lines.append("")

    report_lines.extend([
        "## 4. Critical Reflection & Identified Knowledge Gaps",
    ])
    for note in reflection_notes:
        report_lines.append(f"- {note}")

    report_lines.extend([
        "",
        "## 5. Strategic Recommendations",
        "- Establish continuous monitoring of emerging benchmark datasets.",
        "- Implement automated cross-validation across primary and secondary sources.",
        "- Maintain human-in-the-loop oversight for high-impact decision matrices.",
        "",
        "---",
        "*Generated by AI Labs Deep Research Workflow*"
    ])

    return "\n".join(report_lines)
